package domain

import (
	"context"
	"errors"
	"fmt"
	"time"
)

// AnnouncementState is where an announcement is in its life. It is derived from
// expires_at and revoked_at on every read, never stored.
type AnnouncementState string

const (
	AnnouncementActive  AnnouncementState = "ACTIVE"
	AnnouncementExpired AnnouncementState = "EXPIRED"
	AnnouncementRevoked AnnouncementState = "REVOKED"
)

// Announcement sources; the set is fixed by chk_temple_announcements_source.
const (
	AnnouncementSourceAdmin  = "admin"
	AnnouncementSourceSystem = "system"
)

// Announcement maps a temple_announcements row, joined with its issuing body's
// name. Plain data: no json/db tag — the wire shape is delivery's.
type Announcement struct {
	ID              string
	TempleID        string
	IssuingBodyID   string
	IssuingBodyName string
	Title           string
	Body            string
	Source          string
	PublishedAt     time.Time
	ExpiresAt       time.Time
	RevokedAt       *time.Time
	// CreatedBy is the backoffice account id; nil when Source is system.
	CreatedBy *string
	// State is filled in by the use case on every announcement it returns;
	// repositories leave it empty.
	State AnnouncementState
}

// StateAt derives the state at now: a revoked announcement is REVOKED whatever
// its expiry; otherwise it is ACTIVE strictly before ExpiresAt, EXPIRED from
// ExpiresAt on.
func (a Announcement) StateAt(now time.Time) AnnouncementState {
	switch {
	case a.RevokedAt != nil:
		return AnnouncementRevoked
	case now.Before(a.ExpiresAt):
		return AnnouncementActive
	default:
		return AnnouncementExpired
	}
}

// IssuingBody is a named body of one temple that announcements are issued by.
type IssuingBody struct {
	ID        string
	TempleID  string
	Name      string
	CreatedAt time.Time
}

// NewAnnouncement is what staff submit to publish. The id is generated by the
// repository; PublishedAt and Source are set by the use case. A zero ExpiresAt
// means the field was missing.
type NewAnnouncement struct {
	IssuingBodyID string
	Title         string
	Body          string
	ExpiresAt     time.Time
}

// AnnouncementPatch carries the fields an edit changes; nil means unchanged.
type AnnouncementPatch struct {
	IssuingBodyID *string
	Title         *string
	Body          *string
	ExpiresAt     *time.Time
}

// AnnouncementPage is one page of a temple's announcements, newest first.
type AnnouncementPage struct {
	Items      []Announcement
	Page       int
	PageSize   int
	Total      int
	TotalPages int
}

var (
	// ErrAnnouncementNotFound — no announcement has the requested id.
	ErrAnnouncementNotFound = errors.New("announcement not found")

	// ErrAnnouncementRevoked — a revoked announcement cannot be edited.
	ErrAnnouncementRevoked = errors.New("announcement is revoked")

	// ErrIssuingBodyExists — the temple already has an issuing body of that
	// name (case-insensitive).
	ErrIssuingBodyExists = errors.New("issuing body already exists")

	// ErrInvalidIssuingBody — the issuing body does not belong to the temple.
	ErrInvalidIssuingBody = errors.New("issuing body does not belong to the temple")

	// ErrTempleNotFound — no temple has the requested id.
	ErrTempleNotFound = errors.New("temple not found")

	// ErrInvalidAnnouncement — a form field is missing, blank or out of range.
	// Use AnnouncementInputError to say which; errors.Is still matches this.
	ErrInvalidAnnouncement = errors.New("invalid announcement input")

	// ErrInvalidIssuingBodyName — the issuing body name is blank or too long.
	// Use AnnouncementInputError; errors.Is still matches this.
	ErrInvalidIssuingBodyName = errors.New("invalid issuing body input")
)

// AnnouncementInputError names the rejected request field and why.
type AnnouncementInputError struct {
	Field   string
	Message string
	// Kind is ErrInvalidAnnouncement or ErrInvalidIssuingBodyName.
	Kind error
}

func (e *AnnouncementInputError) Error() string { return fmt.Sprintf("%s: %s", e.Field, e.Message) }

// Unwrap lets errors.Is match the Kind (ErrInvalidAnnouncement by default).
func (e *AnnouncementInputError) Unwrap() error {
	if e.Kind != nil {
		return e.Kind
	}
	return ErrInvalidAnnouncement
}

// AnnouncementRepository is the port the announcement use case works through.
type AnnouncementRepository interface {
	// TempleExists reports whether the temple exists.
	TempleExists(ctx context.Context, templeID string) (bool, error)

	// IssuingBodyBelongs reports whether the issuing body exists and belongs to the temple.
	IssuingBodyBelongs(ctx context.Context, issuingBodyID, templeID string) (bool, error)

	// Insert generates the id, stores a and returns the stored row (with the
	// issuing body name). ErrTempleNotFound when the temple vanished meanwhile.
	Insert(ctx context.Context, a Announcement) (*Announcement, error)

	// FindByID returns the announcement or ErrAnnouncementNotFound.
	FindByID(ctx context.Context, id string) (*Announcement, error)

	// Update writes title, body, issuing body and expiry of a.ID, bumps
	// updated_at, and returns the stored row, or ErrAnnouncementNotFound.
	Update(ctx context.Context, a Announcement) (*Announcement, error)

	// Revoke sets revoked_at to at only if it is still null and returns the
	// row (idempotent), or ErrAnnouncementNotFound.
	Revoke(ctx context.Context, id string, at time.Time) (*Announcement, error)

	// ListByTemple returns limit announcements (any state) from offset, newest
	// published first with id as tie-break, and the total. Past the end is empty.
	ListByTemple(ctx context.Context, templeID string, offset, limit int) ([]Announcement, int, error)
}

// IssuingBodyRepository is the port for a temple's issuing bodies.
type IssuingBodyRepository interface {
	// Insert generates the id and stores the body. ErrIssuingBodyExists on a
	// case-insensitive duplicate, ErrTempleNotFound when the temple does not exist.
	Insert(ctx context.Context, templeID, name string) (*IssuingBody, error)

	// ListByTemple returns the temple's bodies ordered by name, then id.
	ListByTemple(ctx context.Context, templeID string) ([]IssuingBody, error)
}
