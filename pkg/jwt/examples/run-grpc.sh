#!/bin/bash

# Script to run the JWT gRPC example

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/../../.." && pwd)"

echo "========================================"
echo "  JWT gRPC Example"
echo "========================================"
echo ""
echo "Starting gRPC server on port 9090..."
echo ""
echo "This example includes:"
echo "  - Authentication interceptors (unary and stream)"
echo "  - Token validation from metadata"
echo "  - Role-based access control"
echo "  - Optional authentication"
echo "  - Built-in test client demonstrating various scenarios"
echo ""
echo "The example will automatically run a test client that demonstrates:"
echo "  1. Authenticated call with valid token"
echo "  2. Unauthenticated call (should fail)"
echo "  3. Invalid token (should fail)"
echo "  4. Admin-only endpoint"
echo "  5. Non-admin accessing admin endpoint (should fail)"
echo "  6. Token refresh flow"
echo "  7. Custom metadata key extraction"
echo ""
echo "To test with grpcurl:"
echo ""
echo "# First, generate a token (you'll need to call your auth service)"
echo "TOKEN=\"your_jwt_token_here\""
echo ""
echo "# Call GetProfile:"
echo "grpcurl -plaintext \\"
echo "  -H \"authorization: Bearer \$TOKEN\" \\"
echo "  localhost:9090 \\"
echo "  UserService/GetProfile"
echo ""
echo "# Call with custom metadata key:"
echo "grpcurl -plaintext \\"
echo "  -H \"x-api-token: \$TOKEN\" \\"
echo "  localhost:9090 \\"
echo "  UserService/GetProfile"
echo ""
echo "========================================"
echo ""

cd "$PROJECT_ROOT" || exit 1
go run pkg/jwt/examples/grpc/main.go
